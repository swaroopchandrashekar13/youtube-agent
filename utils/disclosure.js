/**
 * Fork rule 7: set YouTube's altered/synthetic-content disclosure whenever AI
 * voice, video or images are part of the published video. Fails safe: an
 * asset whose origin is unknown counts as synthetic.
 */

const NON_SYNTHETIC_AUDIO = new Set(['human', 'recorded', 'none', 'simulation']);
const NON_SYNTHETIC_VIDEO = new Set(['slideshow', 'simulation', 'local', 'user_clips']);

/**
 * @param {{ audio?: object, finalVideo?: object, video?: object }} [assets]
 * @returns {boolean}
 */
function requiresSyntheticDisclosure(assets = {}) {
  const audio = assets.audio || {};
  const hasAudio = Boolean(audio.path) && !audio.intentionalSilence;
  if (hasAudio && !NON_SYNTHETIC_AUDIO.has(String(audio.provider || 'unknown').toLowerCase())) return true;

  const provider = assets.finalVideo?.provider;
  const actual = typeof provider === 'string' ? provider : provider?.actualProvider;
  if (assets.finalVideo?.path && !NON_SYNTHETIC_VIDEO.has(String(actual || 'unknown').toLowerCase())) return true;

  const visuals = Array.isArray(assets.video?.visualAssets) ? assets.video.visualAssets : [];
  // Placeholder visuals are written as *.info files; anything else was generated by an image model.
  return visuals.some(item => typeof item === 'string' && !item.endsWith('.info'));
}

module.exports = { requiresSyntheticDisclosure };
